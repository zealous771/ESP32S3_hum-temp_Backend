"""时间工具。

本模块只有一个函数，但它承载了一条**必须贯穿全工程**的约定：

    凡是"数据什么时候到达后端"这类信息，一律用**后端自己的时钟**，
    绝不用设备报上来的 ts。

为什么这条约定值得单独写一个模块：

    报文里有两个不同的时间概念，它们回答的是完全不同的问题——

      ts           设备**采样**这一刻的时间（设备时钟）
      received_at  后端**收到/入库**这一刻的时间（后端时钟）

    两者相减就是"这条数据在路上走了多久"（含设备本地队列积压 +
    网络传输 + 后端处理）。这个差值本身就是一条重要的运维指标：
    它突然变大说明链路堵了；它一直是负的说明设备时钟快了。

    ★ 更关键的是：**只有后端时钟能发现"设备静默停发"**。

      实测踩到过：设备连续发布 41 分钟后彻底停发，持续 2.5 小时，
      而它本地一切正常（MQTT 连接在、队列零丢弃、串口照常打印）。
      如果表里只有 ts，那段时间就是"没有行"——你无法区分
      "设备没采" 和 "采了没发出来"，更看不出它停了多久。

      有了 received_at 就不一样：查相邻两行的 received_at 差值，
      一个 2.5 小时的断层一眼就能看见，而且能精确定位到从哪一条开始停的。

    反过来，只有 received_at 也不行：设备断网一段时间后重连，
    积压的数据会**集中**入库（received_at 挤在一起），但它们的 ts
    是分散的、真实的。只按 received_at 排序会把历史数据全排到最后，
    时间轴就错了。

    所以两条时间轴都要存，各司其职。查询历史用 ts，排查链路用 received_at。
"""

from __future__ import annotations

import time


def now_ms() -> int:
    """当前时间的 Unix 毫秒数（**后端时钟**）。

    为什么到处都要用它、而不是各自写 ``int(time.time() * 1000)``：

        1. 单位容易搞错——time.time() 是**秒**，忘了乘 1000 会得到一个
           1970 年附近的数，而它看起来完全合法（就是个不大的整数），
           存进库里不会报任何错。收敛到一处就不会有这个失误。

        2. 将来要做"后端时钟与设备时钟的偏差校正"时，只需要改这里。

    注意它**不是**单调时钟（NTP 校时时可能回跳）。用来做"两条数据的
    时间差"没问题（秒级跳变对分钟级的判断无影响），但不要拿它做
    精确的耗时测量——那要用 ``time.monotonic()``。
    """
    return int(time.time() * 1000)
